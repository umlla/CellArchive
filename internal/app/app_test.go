func TestCalcPD(t *testing.T) {
	cases := []struct {
		harvested, inoculum, want float64
	}{
		{4, 4, 0},
		{8, 4, 1},
		{16, 2, 3},
		{1, 4, -2},
		{0, 4, 0},
		{4, 0, 0},
	}
	for _, item := range cases {
		if got := calcPD(item.harvested, item.inoculum); math.Abs(got-item.want) > 0.001 {
			t.Fatalf("calcPD(%v,%v)=%v, want %v", item.harvested, item.inoculum, got, item.want)
		}
	}
}

func TestParseNumberAndDate(t *testing.T) {
	numbers := map[string]float64{
		"5.1X10^5": 510000,
		"5.1×105":  510000,
		"1.2*10^6": 1200000,
		"1,200":    1200,
		"3.5":      3.5,
	}
	for raw, want := range numbers {
		got, ok := parseNumber(raw)
		if !ok || math.Abs(got-want) > 0.001 {
			t.Fatalf("parseNumber(%q)=%v,%v want %v", raw, got, ok, want)
		}
	}
	if _, ok := parseNumber("未知"); ok {
		t.Fatal("parseNumber should reject text")
	}
	dates := map[string]string{
		"2026-04-15": "2026-04-15",
		"2022.4.15":  "2022-04-15",
		"2022/04/15": "2022-04-15",
		"2026-1-5":   "2026-01-05",
		"2026":       "2026-01-01",
		"2026-02":    "2026-02-01",
	}
	for raw, want := range dates {
		got := parseDateValue(raw)
		if got == nil || *got != want {
			t.Fatalf("parseDateValue(%q)=%v want %v", raw, got, want)
		}
	}
	if parseDateValue("不是日期") != nil {
		t.Fatal("parseDateValue should reject text")
	}
}

func TestParseCellText(t *testing.T) {
	parsed := parseCellText("HeLa\n5.1X10^5\nPD=10.26\n2022.4.15\n2023.5.1")
	if parsed == nil || parsed.CellName != "HeLa" {
		t.Fatalf("unexpected parse result: %#v", parsed)
	}
	if parsed.CellCount == nil || math.Abs(*parsed.CellCount-510000) > 0.01 {
		t.Fatalf("cell count = %v", parsed.CellCount)
	}
	if parsed.PD == nil || math.Abs(*parsed.PD-10.26) > 0.001 {
		t.Fatalf("pd = %v", parsed.PD)
	}
	if parsed.FreezeDate == nil || *parsed.FreezeDate != "2022-04-15" {
		t.Fatalf("freeze date = %v", parsed.FreezeDate)
	}
	if parsed.RevivedDate == nil || *parsed.RevivedDate != "2023-05-01" {
		t.Fatalf("revived date = %v", parsed.RevivedDate)
	}
	if parsed.Status != "已复苏" {
		t.Fatalf("status = %s", parsed.Status)
	}
}

